int32_t dptx_sec_set_phy_sigan_quality(const struct Dptx_Params *dev_param,
				       uint32_t lane_idx,
				       uint8_t link_rate,
				       enum PHY_VOLTAGE_SWING_LEVEL voltage_swing,
				       enum PHY_PRE_EMPHASIS_LEVEL pre_emphasis)
{
	int32_t ret = DPTX_RETURN_NO_ERROR;
	uint8_t linear_idx;

	if (dev_param->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_debug("Nothing to do not for Samsung PHY");
	} else {
		if ((uint8_t)voltage_swing >= (uint8_t)VOLTAGE_SWING_LEVEL_MAX) {
			dptx_err("Invalid VSW as %u", (uint8_t)voltage_swing);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			if ((uint8_t)pre_emphasis >= (uint8_t)PRE_EMPHASIS_LEVEL_MAX) {
				dptx_err("Invalid Pre-emp as %u", (uint8_t)pre_emphasis);
				ret = -DPTX_RETURN_EINVAL;
			}
		}
		if (lane_idx > (uint8_t)PHY_LANE_3) {
			dptx_err("Invalid lane idx as %u", lane_idx);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (link_rate > (uint8_t)LINK_RATE_HBR3) {
			dptx_err("Invalid link rate as %u", link_rate);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			linear_idx = ((uint8_t)voltage_swing * 4u) + (uint8_t)pre_emphasis;

			if ((linear_idx == 7u) || (linear_idx == 10u) ||
			    (linear_idx == 11u) || (linear_idx == 13u) ||
			    (linear_idx == 14u) || (linear_idx == 15u) ||
			    (linear_idx >= 16u)) {
				dptx_err("Not allowed voltage swing %u level and pre-emphsis %u level",
					  (uint8_t)voltage_swing, (uint8_t)pre_emphasis);
				ret = -DPTX_RETURN_EINVAL;
			}
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			ret = dptx_sec_set_main_equalization(dev_param, (uint8_t)lane_idx,
					dev_param->hw_config.phy_eq[link_rate].main_eq[linear_idx]);
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			ret = dptx_sec_set_post_equalization(dev_param, (uint8_t)lane_idx,
					dev_param->hw_config.phy_eq[link_rate].post_eq[linear_idx]);
		}
	}
	return ret;
}

void dptx_sec_get_default_phy_eq(const struct Dptx_Params *dev_param,
				 uint32_t default_main_eq[16],
				 uint32_t default_post_eq[16])
{
	if (dev_param->ePhy_Dev == PHY_DEVICE_SEC) {
		(void)memcpy(default_main_eq, default_d5_main_eq, sizeof(uint32_t) * 16u);
		(void)memcpy(default_post_eq, default_d5_post_eq, sizeof(uint32_t) * 16u);
	}
}

