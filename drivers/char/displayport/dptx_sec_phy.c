static void dptx_reset_sec_phy(struct Dptx_Params *pstDptx)
{
	uint32_t reg_wval;

	if (pstDptx->ePhy_Dev == PHY_DEVICE_SEC) {
		reg_wval = ((uint32_t)PHY_CLK_DIV_DISABLE | (uint32_t)LC_REF_RO_PLL);
		(void)Dptx_Cfg_Set_PHY_Cfg(pstDptx, reg_wval);

		reg_wval = ((uint32_t)CFG_LANE_RESET | (uint32_t)CFG_CMN_RESET
			  | (uint32_t)CFG_INT_RESET);
		(void)Dptx_Cfg_SoftReset(pstDptx, reg_wval);

		reg_wval |= (uint32_t)CFG_DP_PHY_APB_RESET;
		(void)Dptx_Cfg_SoftReset(pstDptx, reg_wval);
		udelay(1);

		reg_wval &= ~(uint32_t)CFG_DP_PHY_APB_RESET;
		(void)Dptx_Cfg_SoftReset(pstDptx, reg_wval);
	}
}

static int32_t dptx_sec_set_num_of_lanes(const struct Dptx_Params *pstDptx, uint8_t ucLanes)
{
	uint32_t reg_addr, reg_offset, reg_val;
	int32_t ret = DPTX_RETURN_NO_ERROR;

	if (pstDptx->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_debug("Nothing to do not for Samsung PHY");
	} else {
		if (!IS_OFFSET_WITHIN_LIMIT(pstDptx->uiSEC_PHY_Reg_Offset)) {
			dptx_err("Invalid reg offset as 0x%x",
				  pstDptx->uiRegBank_RegAddr_Offset);
			ret = DPTX_RETURN_EINVAL;
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			reg_addr = pstDptx->uiSEC_PHY_Reg_Offset;
			reg_offset = (uint32_t)SEC_PHY_REG0207;

			switch (ucLanes) {
			case 1u:
				reg_val = 0x01U;
				break;
			case 2u:
				reg_val = 0x03U;
				break;
			case 4u:
				reg_val = 0x0FU;
				break;
			default:
				dptx_err("Invalid Num of lanes as 0x%x", ucLanes);
				ret = -DPTX_RETURN_EINVAL;
				break;
			}

		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			if (IS_OFFSET_OVERFLOW(reg_addr, reg_offset)) {
				dptx_err("Register address overflow: base=0x%x, offset=0x%x",
					  reg_addr, reg_offset);
				ret = -DPTX_RETURN_EINVAL;
			}
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			Dptx_Reg_Writel(pstDptx,
					(reg_addr + reg_offset), reg_val);
		}
	}

	return ret;
}

int32_t Dptx_Sec_PHY_Init(struct Dptx_Params *pstDptx, uint8_t ucLinkRate, uint8_t ucLanes)
{
	uint32_t phy_cfg_val, reg_idx, reg_addr, reg_offset, reg_val;
	const struct sec_phy_reginfo *sec_phy_setup_regs;
	int32_t ret = DPTX_RETURN_NO_ERROR;
	enum PHY_LINK_RATE link_rate;
	bool phy_ready;

	if (pstDptx->ePhy_Dev == PHY_DEVICE_SEC) {
		dptx_reset_sec_phy(pstDptx);

		if (!IS_OFFSET_WITHIN_LIMIT(pstDptx->uiSEC_PHY_Reg_Offset)) {
			dptx_err("Invalid reg offset as 0x%x", pstDptx->uiRegBank_RegAddr_Offset);

			ret = -DPTX_RETURN_EINVAL;
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			dptx_dbg("Init SEC Phy with Max rate(%u) = %s",
				  ucLinkRate,
				  (ucLinkRate == (uint8_t)DPTX_PHYIF_CTRL_RATE_RBR) ? "RBR" :
				  (ucLinkRate == (uint8_t)DPTX_PHYIF_CTRL_RATE_HBR) ? "HBR" :
				  (ucLinkRate == (uint8_t)DPTX_PHYIF_CTRL_RATE_HBR2) ? "HBR2" : "HBR3");

			reg_addr = pstDptx->uiSEC_PHY_Reg_Offset;

			sec_phy_setup_regs = (const struct sec_phy_reginfo *)sec_phy_link_setup_regs;

			/* Set LC (cascade) or RO PLL */
			phy_cfg_val = (ucLinkRate == (uint8_t)DPTX_PHYIF_CTRL_RATE_HBR3) ?
				((uint32_t)PHY_CLK_DIV_DISABLE | (uint32_t)RO_REF_RO_PLL) :
				((uint32_t)PHY_CLK_DIV_DISABLE | (uint32_t)LC_REF_RO_PLL);
			ret = Dptx_Cfg_Set_PHY_Cfg(pstDptx, phy_cfg_val);
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			for (reg_idx = 0u;
			     (sec_phy_setup_regs[reg_idx].reg_offset != (uint32_t)SEC_PHY_REG_MAX);
			     reg_idx++) {
				link_rate = sec_phy_setup_regs[reg_idx].link_rate;
				if ((link_rate != LINK_RATE_MAX) &&
					((uint8_t)link_rate != ucLinkRate)) {
					/*For KCS */
					continue;
				}
				if (sec_phy_setup_regs[reg_idx].reg_offset == (uint32_t)SEC_PHY_DELAY_USEC_REG) {
					udelay(sec_phy_setup_regs[reg_idx].reg_val);
					continue;
				}

				dptx_debug("Reg[0x%x] = 0x%x", sec_phy_setup_regs[reg_idx].reg_offset, sec_phy_setup_regs[reg_idx].reg_val);

				reg_val = sec_phy_setup_regs[reg_idx].reg_val;
				reg_offset = sec_phy_setup_regs[reg_idx].reg_offset;

				Dptx_Reg_Writel(pstDptx, (reg_addr + reg_offset), reg_val);
			}

			/* enable PHY_BIAS and PHY_BGR */
			phy_cfg_val |= ((uint32_t)CFG_BIAS_EN | (uint32_t)CFG_BGR_EN);
			ret = Dptx_Cfg_Set_PHY_Cfg(pstDptx, phy_cfg_val);
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			udelay(10);
			sec_phy_setup_regs = (const struct sec_phy_reginfo *)sec_phy_aux_setup_regs;

			for (reg_idx = 0; (sec_phy_setup_regs[reg_idx].reg_offset != (uint32_t)SEC_PHY_REG_MAX); reg_idx++) {

				link_rate = sec_phy_setup_regs[reg_idx].link_rate;

				if ((link_rate != LINK_RATE_MAX) &&
				    ((uint8_t)link_rate != ucLinkRate)) {
					/*For KCS */
					continue;
				}

				if (sec_phy_setup_regs[reg_idx].reg_offset == (uint32_t)SEC_PHY_DELAY_USEC_REG) {
					udelay(sec_phy_setup_regs[reg_idx].reg_val);
					continue;
				}

				dptx_debug("Reg[0x%x] = 0x%x", sec_phy_setup_regs[reg_idx].reg_offset, sec_phy_setup_regs[reg_idx].reg_val);

				reg_val = sec_phy_setup_regs[reg_idx].reg_val;
				reg_offset = sec_phy_setup_regs[reg_idx].reg_offset;

				Dptx_Reg_Writel(pstDptx, (reg_addr + reg_offset), reg_val);
			}
			/* release PHY_INIT_reset */
			(void)Dptx_Cfg_SoftReset(pstDptx, (uint32_t)(CFG_LANE_RESET | CFG_CMN_RESET | CFG_DP_MB_RESET));
			udelay(10);

			phy_cfg_val |= (uint32_t)CFG_PLL_EN;
			ret = Dptx_Cfg_Set_PHY_Cfg(pstDptx, phy_cfg_val);
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			udelay(10);

			/* release PHY_CMN reset */
			(void)Dptx_Cfg_SoftReset(pstDptx, (uint32_t)CFG_LANE_RESET | (uint32_t)CFG_DP_MB_RESET);

			/* wait o_pll_lock_done and o_pll_clk_rdy */
			ret = Dptx_Cfg_Check_PHY_Pll(pstDptx, &phy_ready);
		}
		if (DPTX_RETURN_SUCCESS(ret) && phy_ready) {
			udelay(10);
			/* release PHY_lane_reset */
			(void)Dptx_Cfg_SoftReset(pstDptx, (uint32_t)CFG_DP_MB_RESET);
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			/* wait o_phy_rdy */
			ret = Dptx_Cfg_Check_PHY_Ready(pstDptx, &phy_ready);
		}
		if (DPTX_RETURN_SUCCESS(ret) && phy_ready) {
			sec_phy_setup_regs = (const struct sec_phy_reginfo *)sec_phy_sb_setup_regs;

			for (reg_idx = 0; (sec_phy_setup_regs[reg_idx].reg_offset != (uint32_t)SEC_PHY_REG_MAX); reg_idx++) {

				link_rate = sec_phy_setup_regs[reg_idx].link_rate;

				if ((link_rate != LINK_RATE_MAX) &&
				    ((uint8_t)link_rate != ucLinkRate)) {
					/*For KCS */
					continue;
				}

				if (sec_phy_setup_regs[reg_idx].reg_offset == (uint32_t)SEC_PHY_DELAY_USEC_REG) {
					udelay(sec_phy_setup_regs[reg_idx].reg_val);
					continue;
				}

				reg_val = sec_phy_setup_regs[reg_idx].reg_val;
				reg_offset = sec_phy_setup_regs[reg_idx].reg_offset;

				if (reg_offset == (uint32_t)SEC_PHY_REG0108) {
					reg_val &= ~((uint32_t)3u << 4);
					reg_val |= ((pstDptx->hw_config.aux_hysteresis & 0x3u) << 4);
				}

				Dptx_Reg_Writel(pstDptx, (reg_addr + reg_offset), reg_val);
			}

			ret = Dptx_Cfg_Check_Sec_PHY_SB_Ready(pstDptx, &phy_ready);
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			/* For KCS */
			ret = dptx_sec_set_num_of_lanes(pstDptx, ucLanes);
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			for (reg_idx = 0; reg_idx < ucLanes; reg_idx++) {
				ret = dptx_sec_set_phy_sigan_quality(pstDptx, reg_idx, ucLinkRate, VOLTAGE_SWING_LEVEL_0, PRE_EMPHASIS_LEVEL_0);
				if (DPTX_RETURN_ERROR(ret)) {
					/* For KCS */
					break;
				}
			}
		}
	}
	return ret;
}

uint32_t dptx_sec_get_main_equalization(const struct Dptx_Params *dptx_params, uint8_t lane_idx)
{
	uint32_t reg_offset, reg_addr;
	uint32_t reg_val = 0u;

	if (dptx_params->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_debug("Nothing to do not for Samsung PHY");
	} else {
		if (lane_idx > (uint8_t)PHY_LANE_3) {
			dptx_err("Invalid lane idx as %u", lane_idx);
		} else {
			if (!IS_OFFSET_WITHIN_LIMIT(dptx_params->uiSEC_PHY_Reg_Offset)) {
				dptx_err("Invalid reg offset as 0x%x", dptx_params->uiRegBank_RegAddr_Offset);
			} else {
				reg_addr = dptx_params->uiSEC_PHY_Reg_Offset;
				reg_offset = dptx_sec_main_reg_offset_table[lane_idx];

				if (IS_OFFSET_OVERFLOW(reg_addr, reg_offset)) {
					dptx_err("Register address overflow: base=0x%x, offset=0x%x",
						  reg_addr, reg_offset);
				} else {
					reg_val = Dptx_Reg_Readl(dptx_params, (reg_addr +  reg_offset));
					reg_val &= 0x1Fu;
				}
			}
		}
	}
	return reg_val;
}

int32_t dptx_sec_set_main_equalization(const struct Dptx_Params *dptx_params, uint8_t lane_idx, uint32_t eq_val)
{
	uint32_t reg_offset, reg_addr, reg_val;
	int32_t ret = DPTX_RETURN_NO_ERROR;

	if (dptx_params->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_debug("Nothing to do not for Samsung PHY");
	} else {
		if (eq_val > 13u) {  /* 0 to 14 */
			dptx_err("Invalid VSW as %u", eq_val);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (lane_idx > (uint8_t)PHY_LANE_3) {
			dptx_err("Invalid lane idx as %u", lane_idx);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			if (!IS_OFFSET_WITHIN_LIMIT(dptx_params->uiSEC_PHY_Reg_Offset)) {
				dptx_err("Invalid reg offset as 0x%x", dptx_params->uiRegBank_RegAddr_Offset);
				ret = -DPTX_RETURN_EINVAL;
			}
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			reg_addr = dptx_params->uiSEC_PHY_Reg_Offset;
			reg_offset = dptx_sec_main_reg_offset_table[lane_idx];

			reg_val = (uint32_t)1u << 5; /* enable overrid */
			reg_val |= (eq_val & 0x1Fu);
			if (IS_OFFSET_OVERFLOW(reg_addr, reg_offset)) {
				dptx_err("Register address overflow: base=0x%x, offset=0x%x",
					  reg_addr, reg_offset);
				ret = -DPTX_RETURN_EINVAL;
			}
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			Dptx_Reg_Writel(dptx_params,
					(reg_addr +  reg_offset), reg_val);
		}
	}
	return ret;
}

